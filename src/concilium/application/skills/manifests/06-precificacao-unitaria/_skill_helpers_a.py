"""Skill 04 — Planejamento e BDI.

Calcula preço unitário (sem e com BDI) por item da EAP, decomposto em 4 categorias:
material, diesel, mão de obra, equipamentos (ADR-023: BDI auditável via TabelaBdi).

Ordem de precedência para BDI:
    1. inputs["bdi_aplicado"]  — override manual (4 categorias flat)
    2. inputs["tabela_bdi"]    — TabelaBdi serializada (ADR-023)
    3. DEFAULT_BDI_TABELA       — valores padrão da planilha rfi_catalog.xlsm (abril/2026)

Mapeamento de categorias ADR-023 -> modelo flat Planejamento.bdi:
    MAO_OBRA  -> mao_obra
    MATERIAL  -> material
    DIESEL    -> diesel
    SERVICOS  -> equipamentos (via tabela_bdi.servicos)
"""

from __future__ import annotations

from typing import Any

from concilium.domain.models.canonical import (
    BdiCategorias,
    CanonicalModel,
    Planejamento,
    PrecoUnitarioCategoria,
    SubtotalCategorias,
    SubtotalSemBdiComBdi,
    ValidacaoItem,
)
from concilium.infrastructure.repositories.insumo import RepositorioInsumo

_CATEGORIA_MAP = {
    "material": "material",
    "diesel": "diesel",
    "mao_obra": "mao_obra",
    "mão_obra": "mao_obra",
    "mao de obra": "mao_obra",
    "mão de obra": "mao_obra",
    "equipamento": "equipamentos",
    "equipamentos": "equipamentos",
}


def _create_synthetic_cpu(cpu_id: str, validacoes: list) -> dict | None:
    """Create synthetic CPU with default structure when not found in catalog.

    ADR-108: Graceful degradation for synthesized CPUs generated by skill-01/05.
    Uses CPU-TERRA-ATI-003-PROD-001 (Desmatamento e Limpeza) as fallback reference.
    """
    # Use TERRA-ATI-003 (desmatamento/limpeza) as universal fallback for synthetic CPUs
    return {
        "codigo": cpu_id,
        "descricao": f"CPU Sintético {cpu_id} (fallback TERRA-ATI-003)",
        "producao_id_ref": "CPU-TERRA-ATI-003-PROD-001",  # Generic fallback: demolition/cleanup
        "composicao_padrao_equipe": {
            "funcoes": [],
            "equipamentos": []
        }
    }


def _resolve_insumo_preco(
    repo: RepositorioInsumo,
    insumo_id: str,
    jurisdicao_id: str | None,
    overrides: dict | None,
    data_base: Any,
    fallback_preco: float,
) -> float:
    try:
        preco_resolvido, _fonte = repo.resolver_preco(
            insumo_id,
            jurisdicao_id=jurisdicao_id,
            overrides=overrides,
            data_referencia=data_base,
        )
        return float(preco_resolvido or fallback_preco or 0.0)
    except Exception:
        return float(fallback_preco or 0.0)


def _build_equipe_lookup(canonical_in: CanonicalModel) -> dict:
    return {eq.item_id: eq for eq in (canonical_in.equipes_diretas or [])}


def _build_planejamento_entry(
    item: Any,
    preco_cat: dict,
    preco_cat_com_bdi: dict,
    bdi_aplicado: dict,
) -> Planejamento:
    q = item.quantitativo
    total_sem_bdi = sum(preco_cat.values())
    total_com_bdi = sum(preco_cat_com_bdi.values())
    return Planejamento(
        item_id=item.item_id,
        cpu_id=item.cpu_id,
        quantitativo=q,
        preco_unitario=PrecoUnitarioCategoria(
            material=round(preco_cat["material"], 4),
            diesel=round(preco_cat["diesel"], 4),
            mao_obra=round(preco_cat["mao_obra"], 4),
            equipamentos=round(preco_cat["equipamentos"], 4),
            total=round(total_sem_bdi, 4),
        ),
        bdi=BdiCategorias(**bdi_aplicado),
        preco_unitario_com_bdi=PrecoUnitarioCategoria(
            material=round(preco_cat_com_bdi["material"], 4),
            diesel=round(preco_cat_com_bdi["diesel"], 4),
            mao_obra=round(preco_cat_com_bdi["mao_obra"], 4),
            equipamentos=round(preco_cat_com_bdi["equipamentos"], 4),
            total=round(total_com_bdi, 4),
        ),
        subtotal=SubtotalSemBdiComBdi(
            sem_bdi=SubtotalCategorias(
                material=round(preco_cat["material"] * q, 2),
                diesel=round(preco_cat["diesel"] * q, 2),
                mao_obra=round(preco_cat["mao_obra"] * q, 2),
                equipamentos=round(preco_cat["equipamentos"] * q, 2),
                total=round(total_sem_bdi * q, 2),
            ),
            com_bdi=SubtotalCategorias(
                material=round(preco_cat_com_bdi["material"] * q, 2),
                diesel=round(preco_cat_com_bdi["diesel"] * q, 2),
                mao_obra=round(preco_cat_com_bdi["mao_obra"] * q, 2),
                equipamentos=round(preco_cat_com_bdi["equipamentos"] * q, 2),
                total=round(total_com_bdi * q, 2),
            ),
        ),
    )


def _try_early_override(
    item: Any,
    planejamento_item_overrides: Any,
    bdi_aplicado: dict,
    validacoes: list,
) -> Planejamento | None:
    _item_ovr_early = (
        planejamento_item_overrides.get(item.item_id, {}) if isinstance(planejamento_item_overrides, dict) else {}
    )
    _pu_early = _item_ovr_early.get("preco_unitario") if isinstance(_item_ovr_early, dict) else None
    if not isinstance(_pu_early, dict):
        return None
    if not any(float(v or 0) != 0 for v in _pu_early.values()):
        return None
    _preco_early = {
        "material": float(_pu_early.get("material", 0.0)),
        "diesel": float(_pu_early.get("diesel", 0.0)),
        "mao_obra": float(_pu_early.get("mao_obra", 0.0)),
        "equipamentos": float(_pu_early.get("equipamentos", 0.0)),
    }
    _com_bdi_early = {cat: _preco_early[cat] * (1 + bdi_aplicado[cat]) for cat in _preco_early}
    validacoes.append(
        ValidacaoItem(
            codigo="VAL-PLAN-OVR-ITEM",
            status="INFO",
            mensagem=f"Item '{item.item_id}': preço unitário sem BDI calibrado por referência.",
        )
    )
    return _build_planejamento_entry(item, _preco_early, _com_bdi_early, bdi_aplicado)


def _apply_equip_decomp(
    ci: Any, insumo: dict, contribuicao: float, preco_cat: dict, equip_sem_decomp_item: set
) -> None:
    decomp_raw = (insumo.get("atributos_especificos") or {}).get("decomposicao_equip")
    if decomp_raw and decomp_raw.get("custo_hora_total", 0.0) > 0:
        total_h = decomp_raw["custo_hora_total"]
        frac_mo = (decomp_raw.get("custo_mao_obra_h", 0.0) + decomp_raw.get("custo_capital_h", 0.0)) / total_h
        frac_die = decomp_raw.get("custo_diesel_h", 0.0) / total_h
        frac_mat = decomp_raw.get("custo_material_h", 0.0) / total_h
        preco_cat["mao_obra"] += contribuicao * frac_mo
        preco_cat["diesel"] += contribuicao * frac_die
        preco_cat["material"] += contribuicao * frac_mat
        preco_cat["equipamentos"] += contribuicao * max(0.0, 1.0 - frac_mo - frac_die - frac_mat)
    else:
        equip_sem_decomp_item.add(ci.insumo_id)
        preco_cat["equipamentos"] += contribuicao


def _compute_preco_cat_from_cpu(
    cpu_model: Any,
    insumo_lookup: dict,
    repo: RepositorioInsumo,
    jurisdicao_id: str | None,
    overrides: dict | None,
    data_base: Any,
    cpu_codigo: str,
    erros_insumo: set,
    validacoes: list,
) -> tuple[dict, set]:
    from concilium.domain.services.conversor_unidades import ConversorUnidades

    preco_cat = {"material": 0.0, "diesel": 0.0, "mao_obra": 0.0, "equipamentos": 0.0}
    equip_sem_decomp_item: set[str] = set()
    for ci in cpu_model.composicao_completa:
        insumo = insumo_lookup.get(ci.insumo_id)
        if insumo is None:
            erros_insumo.add(ci.insumo_id)
            continue
        categoria_raw = (ci.categoria_custo or "").strip().lower()
        categoria = _CATEGORIA_MAP.get(categoria_raw)
        if categoria is None:
            validacoes.append(
                ValidacaoItem(
                    codigo="VAL-PLAN-CAT",
                    status="AVISO",
                    mensagem=(
                        f"CPU '{cpu_codigo}' usa categoria_custo desconhecida:"
                        f" '{ci.categoria_custo}'. Item ignorado no planejamento."
                    ),
                )
            )
            continue
        unidade_insumo = insumo.get("unidade")
        unidade_cpu = ci.unidade or unidade_insumo
        try:
            coeficiente_ajustado = ConversorUnidades.resolver_coeficiente_cpu(
                ci.coeficiente, unidade_cpu, unidade_insumo
            )
            preco_insumo = _resolve_insumo_preco(
                repo, ci.insumo_id, jurisdicao_id, overrides, data_base, float(insumo.get("preco_unitario", 0.0) or 0.0)
            )
            contribuicao = coeficiente_ajustado * preco_insumo
        except Exception as e:
            validacoes.append(
                ValidacaoItem(
                    codigo="VAL-PLAN-UNIT", status="ERRO", mensagem=f"Erro de conversão na CPU '{cpu_codigo}': {e}"
                )
            )
            preco_insumo = _resolve_insumo_preco(
                repo, ci.insumo_id, jurisdicao_id, overrides, data_base, float(insumo.get("preco_unitario", 0.0) or 0.0)
            )
            contribuicao = ci.coeficiente * preco_insumo
        if categoria == "equipamentos":
            _apply_equip_decomp(ci, insumo, contribuicao, preco_cat, equip_sem_decomp_item)
            continue
        preco_cat[categoria] += contribuicao
    return preco_cat, equip_sem_decomp_item


def _compute_preco_cat_from_production(
    cpu: dict,
    prod_lookup: dict,
    insumo_lookup: dict,
    preco_diesel: float,
    alpha_clt: float,
    alpha_mensalista: float,
    validacoes: list,
    catalog_session: object | None = None,  # ADR-100
) -> dict | None:
    """NEP-032 D1: deriva preco_cat da composição da equipe × produtividade (bottom-up canônico).

    Fórmula: PU_categoria = custo_categoria_hora / producao.valor_horario

    Onde custo_categoria_hora é calculado por pu_calculator.calcular_pu():
      MO:         Σ (salario/horas_mes × α × num_pessoas)
      Diesel:     Σ (consumo_L_h × preco_diesel × num_unidades)
      Equipamento: Σ (preco_h × num_unidades)  [parte não-MO/não-diesel]
      Material:   Σ (consumo_h × preco × num_materiais)

    Emite VAL-PLAN-SBDI-LEGADO se o CPU ainda tiver precos_unitarios_sbdi
    hard-coded (campo agora depreciado — não é usado no cálculo).
    """
    from concilium.application.catalog.pu_calculator import ParametrosCalculo, derivar_precos_unitarios_sbdi
    from concilium.domain.constants import ENCARGOS_PJ, HORAS_MES_REGIME_6x1

    prod_id = cpu.get("producao_id_ref")
    if not prod_id:
        return None

    producao = prod_lookup.get(prod_id)
    if not producao:
        return None

    valor_horario = float(producao.get("valor_horario") or 0.0)
    if valor_horario <= 0:
        validacoes.append(
            ValidacaoItem(
                codigo="VAL-PLAN-PROD-HORARIO",
                status="AVISO",
                mensagem=(
                    f"CPU '{cpu.get('codigo')}': producao '{prod_id}' tem valor_horario=0; "
                    "precificação bottom-up impossível."
                ),
            )
        )
        return None

    params = ParametrosCalculo(
        alpha_clt=alpha_clt,
        alpha_pj=ENCARGOS_PJ,
        preco_diesel=preco_diesel,
        horas_mes=HORAS_MES_REGIME_6x1,
    )

    sbdi = derivar_precos_unitarios_sbdi(producao, insumo_lookup, params, catalog_session=catalog_session)
    if not sbdi or float(sbdi.get("total", 0.0) or 0.0) <= 0:
        return None

    preco_cat = {
        "mao_obra": float(sbdi.get("mo", sbdi.get("mao_obra", 0.0)) or 0.0),
        "diesel": float(sbdi.get("diesel", 0.0) or 0.0),
        "equipamentos": float(sbdi.get("equipamentos", 0.0) or 0.0),
        "material": float(sbdi.get("material", 0.0) or 0.0),
    }

    # Advertir se CPU ainda tem sbdi hard-coded (campo legado, ignorado)
    if cpu.get("precos_unitarios_sbdi"):
        validacoes.append(
            ValidacaoItem(
                codigo="VAL-PLAN-SBDI-LEGADO",
                status="INFO",
                mensagem=(
                    f"CPU '{cpu.get('codigo')}': precos_unitarios_sbdi encontrado mas ignorado — "
                    "usando precificação bottom-up canônica (NEP-032)."
                ),
            )
        )

    return preco_cat


def _validate_encargos_separacao(
    cpu_codigo: str,
    cpu: dict,
    insumo_lookup: dict,
    validacoes: list,
) -> None:
    """NEP-031 L5: valida separação entre encargos trabalhistas (α) e BDI de MO.

    Arquitetura correta (dois mecanismos complementares sem sobreposição):
      α (skill-05): converte salário mensal em custo real do trabalhador para a empresa
                    (INSS, FGTS, férias, 13°, SESI, SENAI, etc.)
                    Fórmula: custo_unit = salario × (1 + α)
                    Valores: α_CLT ≈ 1.777, α_mensalista ≈ 1.060, α_PJ ≈ 0.06

      BDI_MO (skill-06): markup do serviço sobre o custo direto de MO
                         (administração central, seguros, risco, lucro, tributos)
                         Fórmula: preco_venda = custo_direto × (1 + BDI_MO)

    RISCO de dupla contagem: se um insumo de MO em composicao_itens tem
    preco_unitario já incluindo encargos (ex: R$/h "all-in" de prestador),
    e o mesmo insumo é processado com BDI_MO pelo skill-06 E também pelo
    skill-05 com α → o custo da mão de obra seria contabilizado duas vezes.

    Heurística de detecção: insumo em composicao_itens com categoria_custo=MAO_OBRA
    e preco_unitario > limiar de salário típico + encargos CLT sugere que encargos
    já estão embutidos (limiar: R$100/h → ~R$16.000/mês para 160h mensais).
    """
    _LIMIAR_PU_MO_H = 100.0  # R$/h — acima disso, encargos provavelmente já incluídos
    for ci in cpu.get("composicao_itens") or []:
        cat = (ci.get("categoria_custo") or "").upper()
        if cat not in {"MAO_OBRA", "MO", "MAO DE OBRA", "MÃO_OBRA"}:
            continue
        iid = ci.get("insumo_id", "")
        ins = insumo_lookup.get(iid)
        if ins is None:
            continue
        preco = float(ins.get("preco_unitario", 0.0) or 0.0)
        unidade = (ins.get("unidade") or "").lower()
        if unidade == "h" and preco > _LIMIAR_PU_MO_H:
            validacoes.append(
                ValidacaoItem(
                    codigo="VAL-PLAN-ENCARGOS-DUPLA",
                    status="AVISO",
                    mensagem=(
                        f"CPU '{cpu_codigo}': insumo '{iid}' tem categoria_custo=MAO_OBRA "
                        f"e preco_unitario={preco:.2f} R$/h (> {_LIMIAR_PU_MO_H} R$/h). "
                        "Possível inclusão de encargos no preço unitário — verifique se "
                        "alpha (encargos trabalhistas de skill-05) não será aplicado em duplicata. "
                        "Se o preço já inclui encargos, defina atributos_especificos.custo_com_encargos "
                        "no insumo para evitar dupla contagem."
                    ),
                )
            )


def _apply_sem_bdi_override(item_id: str, item_override: Any, preco_cat: dict, validacoes: list) -> None:
    override_sem = item_override.get("preco_unitario") if isinstance(item_override, dict) else None
    if not isinstance(override_sem, dict):
        return
    for cat in ("material", "diesel", "mao_obra", "equipamentos"):
        if cat in override_sem:
            try:
                preco_cat[cat] = float(override_sem[cat])
            except Exception:
                pass
    validacoes.append(
        ValidacaoItem(
            codigo="VAL-PLAN-OVR-ITEM",
            status="INFO",
            mensagem=f"Item '{item_id}': preço unitário sem BDI calibrado por referência.",
        )
    )


def _apply_com_bdi_override(
    item_id: str, item_override: Any, preco_cat: dict, bdi_aplicado: dict, validacoes: list
) -> dict:
    override_com = item_override.get("preco_unitario_com_bdi") if isinstance(item_override, dict) else None
    if isinstance(override_com, dict):
        preco_cat_com_bdi = {
            "material": float(override_com.get("material", preco_cat["material"] * (1 + bdi_aplicado["material"]))),
            "diesel": float(override_com.get("diesel", preco_cat["diesel"] * (1 + bdi_aplicado["diesel"]))),
            "mao_obra": float(override_com.get("mao_obra", preco_cat["mao_obra"] * (1 + bdi_aplicado["mao_obra"]))),
            "equipamentos": float(
                override_com.get("equipamentos", preco_cat["equipamentos"] * (1 + bdi_aplicado["equipamentos"]))
            ),
        }
        validacoes.append(
            ValidacaoItem(
                codigo="VAL-PLAN-OVR-ITEM-BDI",
                status="INFO",
                mensagem=f"Item '{item_id}': preço unitário com BDI calibrado por referência.",
            )
        )
    else:
        preco_cat_com_bdi = {cat: preco_cat[cat] * (1 + bdi_aplicado[cat]) for cat in preco_cat}
    return preco_cat_com_bdi


def _validate_coverage(canonical_in: CanonicalModel, plan_out: list, validacoes: list) -> None:
    if not canonical_in.equipes_diretas:
        return
    from concilium.domain.services.validador_cobertura_item import validar_cobertura_item

    equipe_lookup_cob = {eq.item_id: eq for eq in canonical_in.equipes_diretas}
    planejamento_lookup_cob = {p.item_id: p for p in plan_out}
    for item in canonical_in.eap:
        equipe = equipe_lookup_cob.get(item.item_id)
        planej = planejamento_lookup_cob.get(item.item_id)
        if equipe and planej:
            validacoes.extend(validar_cobertura_item(item, equipe, planej))


def _process_eap_item(
    item: Any,
    cpu_lookup: dict,
    insumo_lookup: dict,
    prod_lookup: dict,
    equipe_lookup: dict,
    planejamento_item_overrides: Any,
    bdi_aplicado: dict,
    repo: RepositorioInsumo,
    jurisdicao_id: str | None,
    overrides: dict | None,
    data_base: Any,
    plan_out: list,
    erros_eap: list,
    erros_insumo: set,
    equip_sem_decomp: set,
    validacoes: list,
    benchmark_mode: bool = False,
    preco_diesel: float = 6.20,
    alpha_clt: float = 1.777,
    alpha_mensalista: float = 1.060,
    catalog_session: object | None = None,  # ADR-100
) -> None:
    cpu = cpu_lookup.get(item.cpu_id)
    if cpu is None:
        # ADR-108: Fallback para CPUs sintetizados não encontrados no catálogo
        # Cria CPU sintético com composição padrão para permitir pipeline continuar
        if item.cpu_id.startswith("CPU-"):
            cpu = _create_synthetic_cpu(item.cpu_id, validacoes)
            if cpu:
                # Registrar fallback como aviso
                validacoes.append(
                    ValidacaoItem(
                        codigo="VAL-CPU-SINTETICO",
                        status="AVISO",
                        mensagem=(
                            f"CPU '{item.cpu_id}' não encontrado em catálogo. "
                            "Usando CPU sintético com producao_id_ref padrão."
                        ),
                    )
                )
            else:
                erros_eap.append(item.cpu_id)
                return
        else:
            erros_eap.append(item.cpu_id)
            return
    prod_id_ref = cpu.get("producao_id_ref")
    if not prod_id_ref:
        validacoes.append(
            ValidacaoItem(
                codigo="VAL-PLAN-PROD-REF-01", status="ERRO", mensagem=f"CPU '{cpu.get('codigo')}' sem producao_id_ref."
            )
        )
        return
    if prod_lookup.get(prod_id_ref) is None:
        validacoes.append(
            ValidacaoItem(
                codigo="VAL-PLAN-PROD-REF-02",
                status="ERRO",
                mensagem=f"CPU '{cpu.get('codigo')}' referencia producao_id_ref inexistente: {prod_id_ref}.",
            )
        )
        return
    early = _try_early_override(item, planejamento_item_overrides, bdi_aplicado, validacoes)
    if early is not None:
        plan_out.append(early)
        return
    preco_cat: dict[str, float] | None = None
    equip_sem_decomp_item: set[str] = set()

    # NEP-032 D1: precificação bottom-up canônica.
    # Hierarquia de fontes:
    #   1. derivar_precos_unitarios_sbdi(producao, insumos) — bottom-up via composição da equipe
    #   2. composicao_itens × preco_insumo — fallback para CPUs sem producao completa
    #   precos_unitarios_sbdi hard-coded nos JSONs é campo depreciado (emite VAL-PLAN-SBDI-LEGADO).

    # Fonte 1: bottom-up da composição da equipe (produção + insumos SICRO/SINAPI)
    preco_cat = _compute_preco_cat_from_production(
        cpu,
        prod_lookup,
        insumo_lookup,
        preco_diesel,
        alpha_clt,
        alpha_mensalista,
        validacoes,
        catalog_session=catalog_session,
    )

    if preco_cat is not None:
        validacoes.append(
            ValidacaoItem(
                codigo="VAL-PLAN-BOTTOM-UP",
                status="INFO",
                mensagem=f"Item '{item.item_id}': preço unitário derivado de composição da equipe (NEP-032).",
            )
        )
    else:
        # Fonte 2: composicao_itens × preco_insumo (fallback)
        from concilium.domain.models.catalogo import CPU

        cpu_model = CPU.model_validate(cpu)
        preco_cat, equip_sem_decomp_item = _compute_preco_cat_from_cpu(
            cpu_model,
            insumo_lookup,
            repo,
            jurisdicao_id,
            overrides,
            data_base,
            cpu.get("codigo"),
            erros_insumo,
            validacoes,
        )
        validacoes.append(
            ValidacaoItem(
                codigo="VAL-PLAN-COMPOSICAO-FALLBACK",
                status="AVISO",
                mensagem=(
                    f"CPU '{cpu.get('codigo')}': precificação bottom-up retornou vazio; "
                    "usando composicao_itens como fallback. "
                    "Verifique valor_horario na produção e composicao_padrao_equipe."
                ),
            )
        )
        # NEP-029: rastrear presença/ausência de precos_unitarios_sbdi para auditoria
        if cpu.get("precos_unitarios_sbdi"):
            validacoes.append(
                ValidacaoItem(
                    codigo="VAL-PLAN-SBDI",
                    status="INFO",
                    mensagem=f"CPU '{cpu.get('codigo')}': precos_unitarios_sbdi disponível (informativo; cálculo usa composicao_itens).",
                )
            )
        else:
            validacoes.append(
                ValidacaoItem(
                    codigo="VAL-PLAN-SBDI-MISSING",
                    status="AVISO",
                    mensagem=(
                        f"CPU '{cpu.get('codigo')}': precos_unitarios_sbdi ausente. "
                        "Usando composicao_itens como fonte de precificação."
                    ),
                )
            )

    if preco_cat is None:
        return
    eq_real = equipe_lookup.get(item.item_id)
    _validate_encargos_separacao(cpu.get("codigo", item.cpu_id), cpu, insumo_lookup, validacoes)
    equip_sem_decomp.update(equip_sem_decomp_item)
    item_override = (
        planejamento_item_overrides.get(item.item_id, {}) if isinstance(planejamento_item_overrides, dict) else {}
    )
    _apply_sem_bdi_override(item.item_id, item_override, preco_cat, validacoes)
    preco_cat_com_bdi = _apply_com_bdi_override(item.item_id, item_override, preco_cat, bdi_aplicado, validacoes)
    plan_out.append(_build_planejamento_entry(item, preco_cat, preco_cat_com_bdi, bdi_aplicado))


def _get_bdi_value(manual: dict[str, Any], *keys: str, default: float = 0.0) -> float:
    for key in keys:
        if key in manual and manual.get(key) is not None:
            try:
                return float(manual.get(key) or 0.0)
            except Exception:
                continue
    return float(default)


def _build_lookups(catalogo: dict[str, Any]) -> tuple[dict[str, dict], dict[str, dict], dict[str, dict]]:
    """NEP-032: prod_lookup agora mapeia prod_id → full production dict (não mais float).

    O acesso ao valor_horario deve ser feito via prod.get("valor_horario").
    Mantém retrocompatibilidade: prod_lookup.get(id) is None ainda funciona para
    verificar existência.
    """
    cpus = {c["codigo"]: c for c in catalogo.get("cpus", [])}
    insumos = {i["codigo"]: i for i in catalogo.get("insumos", [])}

    # Produtividades: dict completo por id (para precificação bottom-up, NEP-032)
    prods_raw = catalogo.get("produtividades", []) or catalogo.get("producoes", [])
    produtividades: dict[str, dict] = {}
    for p in prods_raw:
        pid = p.get("id")
        if not pid:
            continue
        # Normaliza campo legado
        if p.get("valor_horario") is None and p.get("producao_horaria") is not None:
            p = {**p, "valor_horario": p["producao_horaria"]}
        produtividades[pid] = p

    return cpus, insumos, produtividades
